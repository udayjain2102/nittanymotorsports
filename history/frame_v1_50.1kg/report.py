"""Write REPORT.md: every design check, the key analysis results, and every pytest test with its outcome,
generated from the code so it is always current. The history (what was done, how, fixes) is PROJECT_LOG.md.
Run: python report.py
"""
import datetime
import pathlib
import pytest
import mule, fea, loads, suspension, rocker, springs, steering, uprights, powertrain, brakes, fab
import cockpit, sideview, mass, harness, shutdown, roll, compliance, lapsim, aero

HERE = pathlib.Path(__file__).parent
MODULES = [(mule, "FSAE rules (V, F, T)"), (suspension, "Suspension kinematics"), (rocker, "Rockers and shocks"),
           (steering, "Steering"), (sideview, "Side view, caster, pitch, steering ratio"), (roll, "Roll, static camber, jacking"),
           (compliance, "Compliance steer and camber (pickup stiffness)"), (uprights, "Uprights and hubs"),
           (powertrain, "Powertrain"), (brakes, "Brakes and pedal box"), (cockpit, "Cockpit templates (T.1.1, T.1.2)"),
           (harness, "Harness (T.2)"), (shutdown, "Shutdown circuit and wiring (IC.9, T.9)"), (aero, "Rear wing and DRS (T.7, IN.6.2)"), (mass, "Mass and CG budget"), (lapsim, "Event simulation (acceleration, skidpad)")]

class Collect:
    def __init__(self): self.rows = []
    def pytest_runtest_logreport(self, report):
        if report.when == "call" or report.outcome != "passed":
            self.rows.append((report.nodeid, report.outcome, round(report.duration, 2)))

def cell(s): return str(s).replace("|", "\\|")

def main():
    rd = (HERE / "README.md").read_text(); a, b = "<!-- colour-key -->", "<!-- /colour-key -->"
    (HERE / "README.md").write_text(rd[:rd.index(a) + len(a)] + "\n" + mule.colour_key_md() + "\n" + rd[rd.index(b):])
    out = [f"# NM26 mule: design report\n",
           f"Generated by `python report.py` on {datetime.date.today()}. It holds every design check the code runs, the key "
           f"analysis results, and every automated test with its outcome. Don't edit it by hand; re-run the script. "
           f"For what was done and why, see [PROJECT_LOG.md](PROJECT_LOG.md). For the physical tests, see [TEST_PLAN.md](TEST_PLAN.md).\n"]
    total = passed = 0; body = []
    for mod, title in MODULES:
        res = mod.checks(); ok = sum(bool(p) for _, p, _ in res); total += len(res); passed += ok
        body += [f"\n### {title} (`{mod.__name__}.py`): {ok}/{len(res)} pass\n", "| | Check | Result |", "|---|---|---|"]
        body += [f"| {'PASS' if p else '**FAIL**'} | {cell(n)} | {cell(d)} |" for n, p, d in res]
    f = fea.run(verbose=False); buck, link, ffos = loads.run(verbose=False)
    pcs = fab.pieces(); frame_kg = sum(fea.props(s)[0] * fea.np.linalg.norm(fea.np.subtract(b, a)) for a, b, s, _ in mule.MEMBERS) * mule.STEEL_DENSITY
    sp = {a: springs.size(a) for a in ("front", "rear")}
    out += ["\n## Key results\n", "| Quantity | Value | From |", "|---|---|---|",
            f"| Frame | {len(mule.MEMBERS)} members, {frame_kg:.1f} kg, {len(pcs)} pieces | `mule.py`, `fab.py` |",
            f"| Torsional stiffness | {f['torsion']:.0f} N·m/deg | `fea.py` |",
            f"| Hoop loads 6/5/9 kN, safety factor | main {f['fos']['Main hoop']:.2f}, front {f['fos']['Front hoop']:.2f} | `fea.py` |",
            f"| Wheel-load cases, worst frame safety factor | {ffos:.2f} | `loads.py` |",
            f"| Worst link buckling safety factor | {buck:.1f} ({link}) | `loads.py` |",
            f"| Springs front / rear | {sp['front']['lbs_in']:.0f} / {sp['rear']['lbs_in']:.0f} lb/in | `springs.py` |",
            f"| Launch, frame safety factor | {powertrain.launch_frame()[0]:.2f} | `powertrain.py` |",
            f"| 2000 N pedal, frame safety factor | {brakes.frame_2000N()[0]:.2f} | `brakes.py` |",
            f"| 20 g harness crash, frame safety factor vs welded UTS | {harness.crash()[0]:.2f} | `harness.py` |",
            f"| Mass, front split, CG height, tilt angle | {mass.summary()['kg']:.0f} kg, {100 * mass.summary()['front']:.1f} %, "
            f"{mass.summary()['cg_h']:.0f} mm, {mass.summary()['tilt']:.1f} deg | `mass.py` |"]
    out += [f"\n## Design checks: {passed}/{total} pass\n"] + body
    col = Collect(); code = pytest.main(["-q", "-p", "no:cacheprovider", str(HERE / "tests")], plugins=[col])
    npass = sum(o == "passed" for _, o, _ in col.rows)
    out += [f"\n## Automated tests (`pytest -q tests`): {npass}/{len(col.rows)} pass\n",
            "Each `test_all_*_checks_pass` test runs one module's checks above; the others test the math directly "
            "(hand calculations, equilibrium, limiting cases).\n", "| Test | Outcome | Seconds |", "|---|---|---|"]
    out += [f"| `{n}` | {'pass' if o == 'passed' else '**' + o + '**'} | {d} |" for n, o, d in col.rows]
    (HERE / "docs" / "REPORT.md").write_text("\n".join(out) + "\n")
    print(f"wrote docs/REPORT.md: {passed}/{total} design checks, {npass}/{len(col.rows)} tests pass")
    return code == 0 and passed == total

if __name__ == "__main__":
    assert main(), "a check or test failed - see REPORT.md"
